import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
const source=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const root=path.dirname(source);
const dictionary=JSON.parse(fs.readFileSync(path.join(source,'src/js/hi.json'),'utf8'));
const runtime=fs.readFileSync(path.join(source,'src/js/preferences.js'),'utf8').replace("import hi from './hi.json';",'const hi='+JSON.stringify(dictionary)+';').replace('export function translate','function translate');
fs.writeFileSync(path.join(root,'preferences.js'),runtime);
fs.copyFileSync(path.join(source,'src/css/preferences.css'),path.join(root,'preferences.css'));
fs.mkdirSync(path.join(source,'public'),{recursive:true});
for(const file of ['privacy.html','disclaimer.html','styles.css','preferences.js','preferences.css'])fs.copyFileSync(path.join(root,file),path.join(source,'public',file));
const result=spawnSync(process.execPath,[path.join(source,'node_modules/vite/bin/vite.js'),'build','--base=./',...process.argv.slice(2)],{cwd:source,stdio:'inherit'});
if(result.status!==0)process.exit(result.status||1);
fs.copyFileSync(path.join(source,'dist/index.html'),path.join(root,'index.html'));
console.log('GitHub Pages files updated in repository root.');
